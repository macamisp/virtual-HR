#!/usr/bin/env node
/**
 * Route-by-permission table (SRS 10.3 RBAC check). Static scan of every NestJS controller:
 * controller prefix, guards, class- and method-level permission decorators, rate-limit buckets.
 * Fails (exit 1) when a route has neither a permission requirement nor an explicit public
 * marker, so the gate can run in CI.
 *
 *   node scripts/route-permissions.mjs > docs/security/route-permissions.md
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../apps/api/src/', import.meta.url));
/** Routes that are public by design (no bearer token). Everything else must name a permission. */
const PUBLIC_BY_DESIGN = new Set([
  'POST /auth/login', 'POST /auth/refresh', 'POST /auth/logout', 'POST /auth/password/forgot', 'POST /auth/password/reset',
  'POST /auth/invitations/accept', 'GET /auth/invitations/:token', 'POST /auth/2fa/verify', 'POST /auth/2fa/setup',
  'GET /share/:token', 'POST /share/:token/open', 'POST /notifications/unsubscribe',
  // ADR 016: LiveKit calls it; the body is verified with the signed sha256 claim.
  'POST /media/livekit/webhook',
  // ADR 018: the desktop agent has no session yet (consent text, pairing code, its own token rotation).
  'GET /agent/notice', 'POST /agent/pair', 'POST /agent/token',
]);
/** Signed-in routes whose scope is "the caller's own data" and need no extra permission. */
const SELF_SERVICE = new Set([
  'GET /users/me', 'GET /me/access', 'GET /me/consents', 'POST /me/consents', 'GET /me/export', 'GET /notifications/preferences', 'PUT /notifications/preferences',
  'POST /auth/2fa/verify', 'POST /auth/2fa/setup', 'GET /attendance/consent', 'GET /attendance/me/events', 'POST /auth/logout',
]);

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* files(p);
    else if (name.endsWith('.controller.ts')) yield p;
  }
}

const METHODS = ['Get', 'Post', 'Put', 'Patch', 'Delete'];
const rows = [];
for (const file of files(ROOT)) {
  const src = readFileSync(file, 'utf8');
  // Split per class: everything from @Controller to the next @Controller.
  const parts = src.split(/(?=@Controller\()/).slice(1);
  for (const part of parts) {
    const prefix = /@Controller\(\s*'([^']*)'\s*\)/.exec(part)?.[1] ?? /@Controller\(\)/.test(part) ? (/@Controller\(\s*'([^']*)'\s*\)/.exec(part)?.[1] ?? '') : '';
    const head = part.slice(0, part.indexOf('export class'));
    const classGuards = /@UseGuards\(([^)]*)\)/.exec(head)?.[1]?.replace(/\s+/g, '') ?? '';
    const classPerm = /@Require(AnyPermission|Permissions)\(([^)]*)\)/.exec(head);
    const classPermText = classPerm ? `${classPerm[1] === 'AnyPermission' ? 'any of ' : ''}${classPerm[2].replace(/Permission\./g, '').replace(/\s+/g, '')}` : '';
    const body = part.slice(head.length);
    // Method decorators: collect decorator blocks preceding each handler.
    const re = /((?:\s*@[A-Za-z]+\([^)]*\)\s*)+)\s*(?:async\s+)?([A-Za-z0-9_]+)\s*\(/g;
    let m;
    while ((m = re.exec(body))) {
      const decorators = m[1];
      const route = new RegExp(`@(${METHODS.join('|')})\\(\\s*(?:'([^']*)')?\\s*\\)`).exec(decorators);
      if (!route) continue;
      const method = route[1].toUpperCase();
      const path = `/${[prefix, route[2] ?? ''].filter(Boolean).join('/')}`.replace(/\/+/g, '/');
      const perm = /@Require(AnyPermission|Permissions)\(([^)]*)\)/.exec(decorators);
      const permText = perm ? `${perm[1] === 'AnyPermission' ? 'any of ' : ''}${perm[2].replace(/Permission\./g, '').replace(/\s+/g, '')}` : classPermText;
      const methodGuards = /@UseGuards\(([^)]*)\)/.exec(decorators)?.[1]?.replace(/\s+/g, '') ?? '';
      const guards = [classGuards, methodGuards].filter(Boolean).join(',');
      const rate = /@RateLimit\('([^']+)'\)/.exec(decorators)?.[1] ?? '';
      const isPublic = /@Public\(\)/.test(decorators) || !/JwtAuthGuard/.test(guards);
      const key = `${method} ${path}`;
      let status = 'OK';
      if (isPublic && !PUBLIC_BY_DESIGN.has(key)) status = 'REVIEW: public route not in allow-list';
      else if (!isPublic && !permText && !SELF_SERVICE.has(key)) status = 'REVIEW: signed-in route without a permission';
      rows.push({ method, path, file: relative(ROOT, file), guards: guards || '(none)', permission: permText || (isPublic ? 'public' : 'signed-in (own data)'), rate, status });
    }
  }
}
rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const bad = rows.filter((r) => r.status !== 'OK');
const out = [
  '# Route-by-permission table',
  '',
  `Generated by \`scripts/route-permissions.mjs\` on ${new Date().toISOString().slice(0, 10)} from every \`*.controller.ts\`. ${rows.length} routes, ${bad.length} needing review.`,
  '',
  'Guards: `JwtAuthGuard` = bearer token required; `PermissionsGuard` = effective permissions resolved per request (ADR 011); `ThrottlerGuard` + bucket = per-IP rate limit. "signed-in (own data)" routes act only on the caller\'s own rows. Data scope inside a route (team vs organisation, RLS) is enforced in the services and proven by the e2e tests.',
  '',
  '| Method | Path | Permission | Guards | Rate limit | Status |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.permission} | ${r.guards} | ${r.rate || '—'} | ${r.status} |`),
  '',
];
process.stdout.write(out.join('\n'));
if (bad.length > 0) {
  process.stderr.write(`${bad.length} route(s) need review:\n${bad.map((r) => `  ${r.method} ${r.path} (${r.file}): ${r.status}`).join('\n')}\n`);
  process.exit(1);
}
